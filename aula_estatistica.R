install.packages("rpart")
install.packages("rpart.plot")
library(rpart.plot)
library(rpart)
filmes <- read.csv("~/aula/movie_blockbusters.csv")
filmes$decade <- factor(filmes$decade, ordered = TRUE)
filmes_filtrado <- c("blockbuster", "decade", "genre", "runtime_min", "budget_usd")
modelo <- rpart(blockbuster ~ ., data = filmes[, filmes_filtrado], method = "class", control = rpart.control(cp = 0.003))
rpart.plot(modelo)
nova_instancia = data.frame(decade = ordered("1980s", levels = levels(filmes$decade)), genre = "Action", runtime_min = 63, budget_usd = 2903222000)
predicao_classe <- predict(modelo, newdata = nova_instancia, type = "prob")
print(predicao_classe)
